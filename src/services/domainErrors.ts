/**
 * domainErrors.ts — خطاهای دامنه‌ای و کدهای استاندارد اعتبارسنجی هسته بیزینس G4X
 */

export enum DomainErrorCode {
  // بازی و سرویس
  GAME_NOT_FOUND = 'GAME_NOT_FOUND',
  GAME_NOT_ACTIVE = 'GAME_NOT_ACTIVE',
  SERVICE_NOT_FOUND = 'SERVICE_NOT_FOUND',
  SERVICE_NOT_ACTIVE = 'SERVICE_NOT_ACTIVE',
  SERVICE_GAME_MISMATCH = 'SERVICE_GAME_MISMATCH',
  SERVICE_MODE_MISMATCH = 'SERVICE_MODE_MISMATCH',

  // تایید صلاحیت و احراز هویت بوستر
  BOOSTER_NOT_APPROVED = 'BOOSTER_NOT_APPROVED',
  PILOT_NOT_APPROVED = 'PILOT_NOT_APPROVED',
  APPROVAL_EXPIRED_OR_SUSPENDED = 'APPROVAL_EXPIRED_OR_SUSPENDED',
  CHARACTER_NOT_OWNED = 'CHARACTER_NOT_OWNED',
  CHARACTER_NOT_FOUND = 'CHARACTER_NOT_FOUND',
  RAIDERIO_SYNC_REQUIRED = 'RAIDERIO_SYNC_REQUIRED',

  // وضعیت و چرخه حیات سفارش
  ORDER_NOT_FOUND = 'ORDER_NOT_FOUND',
  PAYMENT_NOT_VERIFIED = 'PAYMENT_NOT_VERIFIED',
  PRESIGN_WINDOW_CLOSED = 'PRESIGN_WINDOW_CLOSED',
  ORDER_NOT_OPEN_FOR_CLAIMS = 'ORDER_NOT_OPEN_FOR_CLAIMS',
  INVALID_ORDER_TRANSITION = 'INVALID_ORDER_TRANSITION',
  ORDER_ALREADY_CLOSED = 'ORDER_ALREADY_CLOSED',
  INCOMPLETE_RUNS_EXIST = 'INCOMPLETE_RUNS_EXIST',
  ORDER_QUANTITY_MISMATCH = 'ORDER_QUANTITY_MISMATCH',

  // تیم آماده (Squad)
  SQUAD_NOT_FOUND = 'SQUAD_NOT_FOUND',
  SQUAD_NOT_APPROVED = 'SQUAD_NOT_APPROVED',
  SQUAD_GAME_MISMATCH = 'SQUAD_GAME_MISMATCH',
  SQUAD_MEMBER_NOT_ACCEPTED = 'SQUAD_MEMBER_NOT_ACCEPTED',
  UNAUTHORIZED_SQUAD_SUBMITTER = 'UNAUTHORIZED_SQUAD_SUBMITTER',
  SQUAD_MEMBER_NOT_APPROVED = 'SQUAD_MEMBER_NOT_APPROVED',

  // تخصیص و رزرو بوستر (Assignment & Reservation)
  ASSIGNMENT_CONFLICT = 'ASSIGNMENT_CONFLICT',
  BOOSTER_ALREADY_RESERVED = 'BOOSTER_ALREADY_RESERVED',
  ROLE_CAPACITY_EXCEEDED = 'ROLE_CAPACITY_EXCEEDED',
  INVALID_ASSIGNED_ROLE = 'INVALID_ASSIGNED_ROLE',
  CLAIM_NOT_FOUND = 'CLAIM_NOT_FOUND',

  // ران‌ها (Runs)
  RUN_NOT_FOUND = 'RUN_NOT_FOUND',
  RUN_ORDER_MISMATCH = 'RUN_ORDER_MISMATCH',
  RUN_ALREADY_COMPLETED = 'RUN_ALREADY_COMPLETED',
  RUN_CANCELLED = 'RUN_CANCELLED',
  RUN_OPERATOR_UNASSIGNED = 'RUN_OPERATOR_UNASSIGNED',

  // دسترسی و اختیارات (Permissions)
  PERMISSION_DENIED = 'PERMISSION_DENIED',
}

export class DomainError extends Error {
  public readonly code: DomainErrorCode;
  public readonly details?: Record<string, any>;

  constructor(code: DomainErrorCode, message: string, details?: Record<string, any>) {
    super(message);
    this.name = 'DomainError';
    this.code = code;
    this.details = details;
    Object.setPrototypeOf(this, DomainError.prototype);
  }
}
